"""Turns every Cube measure into an OpenMetadata ``Metric`` entity
(ARCHITECTURE.md §7 `catalog/openmetadata/sync` — "Cube meta -> Metric
entities" — and the M2 build-order item, §8). Cube is the single definition
of every metric (ADR-0003); this sync is what makes that definition visible
to the discovery MCP the chatbot reads (§6), same job
``openmetadata_dagster_sync`` does for the Dagster asset catalog and
``openmetadata_sync`` does for Snowflake/dbt.

Bespoke, like ``openmetadata_dagster_sync``, not run through
``MetadataWorkflow``: ``openmetadata-ingestion==2.0.1`` ships no Cube source
connector, so there is no ``Source``/``Sink`` pipeline to configure. Instead
this reads Cube's own REST metadata endpoint
(``GET {CUBEJS_API_URL}/cubejs-api/v1/meta``, authenticated the same way any
Cube API caller is — a JWT signed with ``CUBEJS_API_SECRET``, ADR-0003 §consequences,
platform/helm/charts/cube/templates/NOTES.txt) and writes ``Metric`` entities
via OpenMetadata's SDK directly.

Cube's meta endpoint deliberately never exposes each measure's underlying SQL
(``sql``/``sql_table``) over the API, so ``metricExpression`` is left unset
rather than faked from the measure's name. The underlying Snowflake table is
instead resolved from the same compiled dbt manifest ``openmetadata_dbt_sync``
already reads (``_dbt_project.manifest_path``, baked into this image at build
time): for any cube generated by cube-dbt's ``{{ model.as_cube() }}``
(confirmed against ``cube_dbt.model.Model._as_cube`` — it sets the cube's
``name`` to the dbt model's own manifest ``name``, verbatim), the cube's name
is exactly that dbt model's name, so it can be looked up in the manifest
directly and joined to the ``Table`` entity ``openmetadata_snowflake_sync``
already ingested for it — no Cube API involvement, no guessing a name
mapping. A hand-written cube with no matching dbt model (or a model not
ingested into OM yet) just gets no table, the same graceful-skip
``openmetadata_dagster_sync`` uses when a downstream Snowflake table isn't
ingested yet.

That resolved table is used two ways, both needed: it's set as the Metric's
``assets`` (the flat "what this metric is computed from" reference OM shows
on the metric's own page), and a separate ``AddLineageRequest`` edge is drawn
from the ``Table`` to the ``Metric`` (the same ``metadata.add_lineage`` call
``openmetadata_dagster_sync`` uses for its own APIEndpoint -> Table edges).
``assets`` alone does *not* populate OM's lineage graph — it's a plain
entity-reference field, not a relationship the Lineage tab or
``get_entity_lineage`` traverses — so skipping the explicit edge leaves a
Metric with `assets` set but invisible in the UI's Lineage view and in any
lineage-graph traversal from the table's side.

One ``Metric`` per Cube measure, named ``<cube>__<measure>`` (Cube's own
fully-qualified ``<cube>.<measure>`` with the dot swapped for a double
underscore — ``Metric`` has no parent service, so its name doubles as its
FQN, and a literal dot there would collide with FQN part-separation). Every
dimension on a measure's own cube is attached to it as a ``MetricDimension``
— Cube has no notion of "this dimension only applies to that measure", so
all of a cube's dimensions apply to all of its measures. Every measure is
also cross-linked (``relatedMetrics``) to every *other* measure in the same
cube, for the same reason: Cube's meta endpoint has no finer-grained notion
of "these two measures are related" than "they're on the same cube," so
same-cube is the only grouping this sync can read off honestly. No
cross-cube relations are drawn.

The job/schedule for this asset live in ``ohdp_orchestration.jobs``/
``.schedules``, not here — this module is asset bodies only
(``ohdp_orchestration.assets``'s own convention, see its ``__init__.py``).
"""

